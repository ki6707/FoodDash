export function getRestaurantImage(restaurant) {
  return FOOD_IMAGES[restaurant?.imageKey ?? restaurant?.category] ?? FOOD_IMAGES.biryani;
}

export function getDishImage(name, fallbackCategory) {
  const dish = name.toLowerCase();
  if (/tiramisu/.test(dish)) return FOOD_IMAGES.tiramisu;
  if (/filter coffee/.test(dish)) return FOOD_IMAGES.filterCoffee;
  if (/chocolate shake|milkshake/.test(dish)) return FOOD_IMAGES.milkshake;
  if (/medu vada/.test(dish)) return FOOD_IMAGES.friedSnack;
  if (/gobi manchurian/.test(dish)) return FOOD_IMAGES.cauliflowerBites;
  if (/chilli chicken/.test(dish)) return FOOD_IMAGES.spicyChicken;
  if (/gulab jamun|payasam/.test(dish)) return FOOD_IMAGES.indianSweets;
  if (/full meals/.test(dish)) return FOOD_IMAGES.southIndianMeal;
  if (/mini tiffin/.test(dish)) return FOOD_IMAGES.idli;
  if (/curd rice/.test(dish)) return FOOD_IMAGES.curdRice;
  if (/garlic bread/.test(dish)) return FOOD_IMAGES.garlicBread;
  if (/fried rice/.test(dish)) return FOOD_IMAGES.friedRice;
  if (/fries/.test(dish)) return FOOD_IMAGES.fries;
  if (/wings/.test(dish)) return FOOD_IMAGES.chickenWings;
  if (/naan/.test(dish)) return FOOD_IMAGES.naan;
  if (/paneer|tikka/.test(dish)) return FOOD_IMAGES.paneerTikka;
  if (/idli/.test(dish)) return FOOD_IMAGES.idli;
  if (/pizza/.test(dish)) return FOOD_IMAGES.pizza;
  if (/burger/.test(dish)) return FOOD_IMAGES.burger;
  if (/dosa/.test(dish)) return FOOD_IMAGES.south;
  if (/noodles/.test(dish)) return FOOD_IMAGES.chinese;
  if (/manchurian/.test(dish)) return FOOD_IMAGES.cauliflowerBites;
  if (/cake|brownie|chocolate|jamun|cheesecake|dessert|payasam/.test(dish)) return FOOD_IMAGES.dessert;
  return FOOD_IMAGES[fallbackCategory] ?? FOOD_IMAGES.biryani;
}